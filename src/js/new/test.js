const config = {
  getDistance: () => gsap.utils.random(5, 10),
  deepFront: 20,
  getDeepBack: () => gsap.utils.random(-10, 10),
  radiusBack: 0.5,
  radiusFront: 3,
  duration: 1,
  ease: 'power2.out',
  stagger: {
    each: 0.001,
    from: "random",
  },
};


function init({ animate = true, staticFinal = false } = {}) {
  const canvas = document.getElementById("canvas");
  if (!canvas) return;
  const ctx = canvas.getContext("2d");

  const baseW = pattern.width;
  const baseH = pattern.height;

  // === Точки ===
  const points = [];
  pattern.points.forEach((item, index) => {
    item.forEach((point, pointIndex) => {
      const distance = config.getDistance();
      const deepFront = config.deepFront;
      const deepBack = config.getDeepBack();
      const radiusBack = config.radiusBack;
      const radiusFront = config.radiusFront;

      const zDirection = pointIndex % 2 !== 0;

      let offsetX = 0;
      let offsetY = 0;

      if (index === 0) {
        offsetX = zDirection ? -deepFront : deepBack;
        offsetY = zDirection ? -deepFront : deepBack;
      }
      if (index === 1) {
        offsetX = zDirection ? deepFront : deepBack;
        offsetY = zDirection ? deepFront : deepBack;
      }
      if (index === 2) {
        offsetX = zDirection ? deepFront : deepBack;
        offsetY = zDirection ? -deepFront : deepBack;
      }
      if (index === 3) {
        offsetX = zDirection ? -deepFront : deepBack;
        offsetY = zDirection ? deepFront : deepBack;
      }

      points.push({
        // На мобилке (staticFinal) — сразу ставим точки в финальные координаты,
        // без «разбросанного» начального состояния
        x: staticFinal ? point.x : point.x + offsetX * distance,
        y: staticFinal ? point.y : point.y + offsetY * distance,
        r: staticFinal ? point.r : point.r * (zDirection ? radiusFront : radiusBack),
        targetX: point.x,
        targetY: point.y,
        targetR: point.r,
        opacity: staticFinal ? 0.5 : 1,
      });
    });
  });

  // === Отрисовка кадра ===
  function drawFrame() {
    ctx.clearRect(0, 0, baseW, baseH);

    const gradient = ctx.createLinearGradient(0, 0, baseW, baseH);
    gradient.addColorStop(0, "#2e00a4");
    gradient.addColorStop(0.25, "#7815ea");
    gradient.addColorStop(0.5, "#d4d6f3");
    gradient.addColorStop(1, "#2e00a4");

    ctx.fillStyle = gradient;

    for (const point of points) {
      ctx.save();
      ctx.globalAlpha = point.opacity;
      ctx.beginPath();
      ctx.arc(point.x, point.y, point.r, 0, Math.PI * 2);
      ctx.closePath();
      ctx.clip();
      ctx.fillRect(0, 0, baseW, baseH);
      ctx.restore();
    }

    ctx.globalAlpha = 1;
  }

  // === Пересчёт размера canvas ===
  function resizeCanvas() {
    const rect = canvas.getBoundingClientRect();
    const logicalW = rect.width;
    const logicalH = rect.height;

    if (logicalW === 0 || logicalH === 0) return;

    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    const physW = Math.round(logicalW * dpr);
    const physH = Math.round(logicalH * dpr);

    if (canvas.width === physW && canvas.height === physH) return;

    canvas.width = physW;
    canvas.height = physH;

    const scaleX = physW / baseW;
    const scaleY = physH / baseH;

    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.scale(scaleX, scaleY);

    drawFrame();
  }

  const heroContainer = document.querySelector('.hero__container');

  // === Анимация (только на десктопе) ===
if (animate) {
  const heroContainer = document.querySelector('.hero__container');

  gsap.to(points, {
    x: (_, point) => point.targetX,
    y: (_, point) => point.targetY,
    r: (_, point) => point.targetR,
    opacity: 0.5,
    duration: config.duration,
    ease: config.ease,
    stagger: config.stagger,
    onUpdate: drawFrame,
    onComplete: () => {
      if (heroContainer) {
        gsap.to(heroContainer, {
          opacity: 1,
          duration: 0.8,
          ease: 'power2.out',
          delay: 0.1,
        });
      }
    },
  });
} else {
  // На мобилке — показываем контейнер сразу
  const heroContainer = document.querySelector('.hero__container');
  if (heroContainer) heroContainer.style.opacity = '1';
}

  // Первичная установка
  resizeCanvas();

  // === Реакция на изменение размера ===
  const bg = canvas.closest(".hero__bg") || canvas;

  if (typeof ResizeObserver !== "undefined") {
    let rafId = null;
    const ro = new ResizeObserver(() => {
      if (rafId) cancelAnimationFrame(rafId);
      rafId = requestAnimationFrame(resizeCanvas);
    });
    ro.observe(bg);
  } else {
    let rafId = null;
    window.addEventListener("resize", () => {
      if (rafId) cancelAnimationFrame(rafId);
      rafId = requestAnimationFrame(resizeCanvas);
    }, { passive: true });
  }
}

document.addEventListener("DOMContentLoaded", function () {
  const canvas = document.getElementById("canvas");
  if (!canvas) return;

  // Запускаем только один раз
  if (canvas.dataset.animated === "true") return;
  canvas.dataset.animated = "true";

  // На мобилке — без анимации (просто статичный фон)
  const isMobile = window.matchMedia("(max-width: 767px)").matches;

  init({
    animate: !isMobile,
    staticFinal: isMobile,
  });
});